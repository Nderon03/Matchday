// Writes the migration that limits profiles.nationality / profiles.supported_club to the
// lists the app ships (src/data/countries.ts, src/data/clubs.ts). Re-run with a new migration
// file name whenever a club or country is added:  node scripts/generate-identity-sql.mjs <file>
import { writeFileSync } from 'node:fs';
import { COUNTRIES } from '../src/data/countries.ts';
import { CLUB_ROWS } from '../src/data/clubs.ts';

const out = process.argv[2] ?? 'supabase/migrations/20261101000031_nationality_club.sql';
const list = (xs) => xs.map((x) => `'${x.replace(/'/g, "''")}'`).join(', ');
const sql = `-- Optional nationality (flag) and supported club on a player's profile and card.
-- Generated by scripts/generate-identity-sql.mjs from the lists the app ships.

alter table public.profiles add column if not exists nationality text;
alter table public.profiles add column if not exists supported_club text;

alter table public.profiles drop constraint if exists profiles_nationality_check;
alter table public.profiles add constraint profiles_nationality_check check (nationality is null or nationality in (
  ${list(COUNTRIES.map((c) => c.code))}
));

alter table public.profiles drop constraint if exists profiles_supported_club_check;
alter table public.profiles add constraint profiles_supported_club_check check (supported_club is null or supported_club in (
  ${list(CLUB_ROWS.map((c) => c[0]))}
));

-- players edit these themselves, like the rest of their profile
grant update (nationality, supported_club) on public.profiles to authenticated;
`;
writeFileSync(out, sql);
console.log('wrote', out, COUNTRIES.length, 'countries', CLUB_ROWS.length, 'clubs');
