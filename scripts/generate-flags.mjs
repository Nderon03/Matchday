// Builds src/data/countries.ts from the country-flag-icons package (MIT, catamphetamine):
//   npm pack country-flag-icons && tar xzf country-flag-icons-*.tgz && node scripts/generate-flags.mjs package
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join(process.argv[2] ?? 'package', '3x2');
const names = new Intl.DisplayNames(['en'], { type: 'region' });
const SKIP = new Set(['EU', 'UN', 'EZ', 'QO', 'AC', 'CP', 'DG', 'EA', 'IC', 'TA', 'XC', 'XO', 'ES-CT', 'BQ-BO', 'BQ-SA', 'BQ-SE']);
const OVERRIDE = { 'GB-ENG': 'England', 'GB-SCT': 'Scotland', 'GB-WLS': 'Wales', 'GB-NIR': 'Northern Ireland', XK: 'Kosovo', PS: 'Palestine', CI: 'Côte d’Ivoire', CD: 'DR Congo', CG: 'Congo', MM: 'Myanmar', HK: 'Hong Kong', MO: 'Macau' };
const rows = [];
for (const f of readdirSync(dir).filter((f) => f.endsWith('.svg'))) {
  const code = f.slice(0, -4);
  if (SKIP.has(code)) continue;
  let name = OVERRIDE[code];
  if (!name) { try { name = names.of(code); } catch { name = null; } }
  if (!name || name === code) continue;
  const svg = readFileSync(join(dir, f), 'utf8').replace(/\s*\n\s*/g, ' ').replace(/>\s+</g, '><').trim();
  rows.push([code, name.replace(/ SAR China$/, ''), svg]);
}
rows.sort((a, b) => a[1].localeCompare(b[1], 'en'));
const out = `// Generated by scripts/generate-flags.mjs. Flags: country-flag-icons (MIT, https://github.com/catamphetamine/country-flag-icons).
export interface Country { code: string; name: string; svg: string }
export const COUNTRIES: Country[] = ${JSON.stringify(rows.map(([code, name, svg]) => ({ code, name, svg })))};
export const COUNTRY_BY_CODE: Record<string, Country> = Object.fromEntries(COUNTRIES.map((c) => [c.code, c]));
`;
writeFileSync('src/data/countries.ts', out);
console.log(rows.length, 'countries');
